function pickMessage(jobType, profile, context = {}) {
  const pool = POOLS[jobType];
  if (!pool || pool.length === 0) return null;

  const currentIndex = profile?.last_message_index?.[jobType] || 0;
  const nextIndex = (currentIndex + 1) % pool.length;
  const raw = pool[nextIndex];

  const name = (profile?.name || 'Creator').split(' ')[0];

  let text = raw
    .replace(/\{\{name\}\}/g, name)
    .replace(/\{\{streak\}\}/g, String(context.streak ?? 0))
    .replace(/\{\{partner\}\}/g, context.partner || 'Your partner')
    .replace(/\{\{challenge\}\}/g, context.challenge || 'your challenge')
    .replace(/\{\{remaining\}\}/g, String(context.remaining ?? 0))
    .replace(/\{\{posts\}\}/g, String(context.posts ?? 0))
    .replace(/\{\{rate\}\}/g, String(context.rate ?? 0))
    .replace(/\{\{tokens\}\}/g, String(context.tokens ?? 0));

  if (!profile?.use_emojis) {
    text = text.replace(/[🔥⏳🎯📌🚀🌅💪⏰🎬🧠🌙😬🔔💎⚡🌆🚨💤👀🏃🤝📣⚔️🌊👊💔🌱🫂🧭🔄📖🤍🏆⚡👑🎖️📊📈🗓️🌟]/g, '').trim();
  }

  return { text, nextIndex };
}

function buildIndexUpdate(profile, jobType, nextIndex) {
  const current = profile?.last_message_index || {};
  return { ...current, [jobType]: nextIndex };
}

